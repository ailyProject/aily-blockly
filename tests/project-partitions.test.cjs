const { ensureProjectPartitionFile: prepare } = require('../src/app/services/domains/project/project-partitions.ts');
const { allocatePartitions, createPreset, serializePartitions, parsePartitionCsv, validatePartitions } = require('../src/app/services/shared/partitions/partition-layout.ts');
const { captureSnapshot } = require('../electron/cloud-build/snapshot');
const protocol = require('../electron/cloud-build/protocol');
const valid = serializePartitions(allocatePartitions(createPreset('iot', 4 * 1024 * 1024)).rows);
function fixture(t, { cloud = false, coder = false, flash = '4M' } = {}) {
  const base = path.join(__dirname, '.artifacts/partitions'); fs.mkdirSync(base, { recursive: true });
  const root = fs.mkdtempSync(path.join(base, 'case-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
  const board = { core: 'esp32:esp32', type: 'esp32:esp32:esp32s3' };
  const boardModule = '@aily-project/board-test', boardRoot = path.join(root, 'node_modules', boardModule);
  const boardPkg = { name: boardModule, version: '1.0.0' };
  write(path.join(boardRoot, 'package.json'), JSON.stringify(boardPkg)); write(path.join(boardRoot, 'board.json'), JSON.stringify(board));
  const pkg = { name: 'test', dependencies: { [boardModule]: '1.0.0' }, projectConfig: { PartitionScheme: 'custom', ...(flash ? { FlashSize: flash } : {}) },
    ...(coder ? { type: 'coder', framework: 'arduino', entry: 'src/main.cpp' } : {}) };
  const manifest = () => write(path.join(root, 'package.json'), JSON.stringify(pkg)); manifest();
  const entry = coder ? 'sketch/src/main.cpp' : 'src/main.cpp'; const code = 'void setup() {}\nvoid loop() {}'; write(path.join(root, entry), code);
  const file = path.join(path.dirname(path.join(root, entry)), 'partitions.csv');
  const profile = { runner: 'aily-builder', boardModule, boardVersion: '1.0.0', boardDigest: protocol.boardDigest(boardPkg, board), metadata: { boardOptions: { PartitionScheme: {}, FlashSize: {} } } };
  const project = { currentProjectPath: root, currentBoardConfig: board,
    isCloudBuild: () => cloud, getPackageJson: async () => structuredClone(pkg), isAilyCodeProject: () => coder,
    getEffectivePackageText: () => JSON.stringify(pkg),
    getBoardFile: async () => fs.existsSync(path.join(boardRoot, 'partitions.csv')) ? path.join(boardRoot, 'partitions.csv') : null,
    getBoardConfigMenu: async () => [{ key: 'PartitionScheme', children: [{ data: 'default' }, { data: 'custom', check: true }] }],
    getSdkPath: async () => path.join(root, 'sdk'), getBoardBuildProperties: async () => ({ 'build.partitions': 'default', 'build.flash_size': flash }),
    getCloudPartitionTemplate: async () => null };
  return { root, boardRoot, file, pkg, manifest, write, project, snapshot: () => captureSnapshot({ currentProjectPath: root, boardModule, code }, profile),
    prepare: () => prepare(project, fs, path) };
}
test('missing CSV fails cloud capture before preparation; generated bytes are captured and alter input identity', async t => {
  const f = fixture(t, { cloud: true });
  assert.throws(f.snapshot, /Custom partition source is unavailable/);
  assert.equal((await f.prepare()).source, 'generated');
  const csv = fs.readFileSync(f.file, 'utf8'); assert.equal(csv, valid);
  const before = f.snapshot(); const input = before.files.find(file => file.path === 'sketch/partitions.csv');
  assert.equal(Buffer.from(input.dataBase64, 'base64').toString(), csv);
  f.write(f.file, csv + '# edited in Dock\n');
  assert.notEqual(f.snapshot().inputDigest, before.inputDigest);
});
for (const cloud of [false, true]) test(`${cloud ? 'cloud' : 'local'} preserves existing source and copies board bytes only when missing`, async t => {
  const f = fixture(t, { cloud }); f.write(path.join(f.boardRoot, 'partitions.csv'), valid);
  assert.equal((await f.prepare()).source, 'board'); assert.equal(fs.readFileSync(f.file, 'utf8'), valid);
  f.write(f.file, 'user-owned even if invalid'); const before = fs.statSync(f.file).mtimeMs;
  assert.equal((await f.prepare()).created, false); assert.equal(fs.readFileSync(f.file, 'utf8'), 'user-owned even if invalid'); assert.equal(fs.statSync(f.file).mtimeMs, before);
});
test('legacy root CSV migrates before board fallback', async t => {
  const f = fixture(t); f.write(path.join(f.root, 'partitions.csv'), valid + '# legacy\n'); f.write(path.join(f.boardRoot, 'partitions.csv'), valid);
  assert.equal((await f.prepare()).source, 'legacy'); assert.equal(fs.readFileSync(f.file, 'utf8'), valid + '# legacy\n');
});
for (const cloud of [false, true]) test(`${cloud ? 'cloud metadata' : 'SDK'} template is used only if it fits the selected Flash`, async t => {
  const f = fixture(t, { cloud });
  if (cloud) f.project.getCloudPartitionTemplate = async () => valid + '# SDK\n';
  else f.write(path.join(f.root, 'sdk/tools/partitions/default.csv'), valid + '# SDK\n');
  assert.equal((await f.prepare()).source, cloud ? 'cloud' : 'sdk'); assert.match(fs.readFileSync(f.file, 'utf8'), /# SDK/);
  fs.unlinkSync(f.file); f.pkg.projectConfig.FlashSize = '8M'; f.manifest();
  f.project.getBoardBuildProperties = async () => ({ 'build.partitions': 'default', 'build.flash_size': '8M' });
  const oversized = serializePartitions(allocatePartitions(createPreset('iot', 16 * 1024 * 1024)).rows);
  if (cloud) f.project.getCloudPartitionTemplate = async () => oversized;
  else f.write(path.join(f.root, 'sdk/tools/partitions/default.csv'), oversized);
  assert.equal((await f.prepare()).source, 'generated');
  assert.deepEqual(validatePartitions(parsePartitionCsv(fs.readFileSync(f.file, 'utf8')).rows, 8 * 1024 * 1024).errors, []);
});
